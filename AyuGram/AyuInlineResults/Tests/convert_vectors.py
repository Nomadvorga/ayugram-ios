#!/usr/bin/env python3
"""Turns the vector calls of exteraGram's Tools/inline/MathExpressionTests.kt into Swift.

    git -C <exteraGram> show HEAD:Tools/inline/MathExpressionTests.kt > /tmp/MathExpressionTests.kt
    python3 convert_vectors.py /tmp/MathExpressionTests.kt > Vectors.swift

Only the plain calls (expr, ghost, money, full, inserted, section, check) are converted. Lines that need
hand-written Swift are listed in MANUAL; anything else that is not recognised stops the conversion. Of the
last section only the table of documented answers is converted.
"""
import re
import sys

STRING = re.compile(r'"(?:[^"\\]|\\.)*"')
CALLS = ("expr(", "ghost(", "money(", "full(", "inserted(", "section(", "check(")

PAIR = re.compile(r'^("(?:[^"\\]|\\.)*") to ("(?:[^"\\]|\\.)*"),?$')

MANUAL = {
    'val twoPowers = "Сначала 2⁵ =; затем 3² ="': [
        'let twoPowers = "Сначала 2⁵ =; затем 3² ="',
    ],
    "val firstEquals = twoPowers.indexOf('=') + 1": [
        'let firstEquals = mathCharacters(twoPowers).firstIndex(of: "=")! + 1',
    ],
    "val firstPower = MathExpression.suggestionAt(twoPowers, firstEquals, MathOptions(grouping = false))": [
        "let firstPower = MathExpression.suggestionAt(twoPowers, caret: firstEquals, options: MathOptions(grouping: false))",
    ],
    "val withFirstAnswer = firstPower?.let {": [
        "let withFirstAnswer: String? = firstPower.map { suggestion in",
        "    var characters = mathCharacters(twoPowers)",
        "    characters.insert(contentsOf: mathCharacters(suggestion.insertText), at: suggestion.insertAt)",
        "    return String(characters)",
        "}",
    ],
    "StringBuilder(twoPowers).insert(it.insertAt, it.insertText).toString()": [],
    "}": [],
    'withFirstAnswer?.let { ghost(it, "9") }': [
        "if let withFirstAnswer {",
        '    ghost(withFirstAnswer, "9")',
        "}",
    ],
    """check("format(NaN)", null, MathFormat.format(Double.NaN, '.'))""": [
        'check("format(NaN)", nil, MathFormat.format(Double.nan, decimalSeparator: "."))',
    ],
    """check("format(Infinity)", null, MathFormat.format(Double.POSITIVE_INFINITY, '.'))""": [
        'check("format(Infinity)", nil, MathFormat.format(Double.infinity, decimalSeparator: "."))',
    ],
    """check("formatMoney(1500) separator", "1\u00a0500", MathFormat.formatMoney(1500.0, 2, '.'))""": [
        'check("formatMoney(1500) separator", "1\\u{00A0}500", MathFormat.formatMoney(1500.0, fractionDigits: 2, decimalSeparator: "."))',
    ],
    """check("money label separator", "8\u00a0000\u00a0₽", MathExpression.suggestionAt("100$=", 5, MathOptions('.', rates, "RUB"))?.value)""": [
        'check("money label separator", "8\\u{00A0}000\\u{00A0}₽", MathExpression.suggestionAt("100$=", caret: 5, options: MathOptions(decimalSeparator: ".", rates: rates, localCurrency: "RUB"))?.value)',
    ],
}


def convert_string(literal):
    return re.sub(r"\\u([0-9A-Fa-f]{4})", lambda m: "\\u{" + m.group(1) + "}", literal)


def convert_code(code):
    code = re.sub(r"'(.)'", r'"\1"', code)
    code = re.sub(r"\b([a-z]\w*) = ", r"\1: ", code)
    code = re.sub(r"\bnull\b", "nil", code)
    return code


def convert_line(line):
    parts = []
    last = 0
    for match in STRING.finditer(line):
        parts.append(convert_code(line[last:match.start()]))
        parts.append(convert_string(match.group(0)))
        last = match.end()
    parts.append(convert_code(line[last:]))
    result = "".join(parts)
    result = re.sub(r'("(?:[^"\\]|\\.)*")\.repeat\((\d+)\)', r"String(repeating: \1, count: \2)", result)
    result = re.sub(r'("(?:[^"\\]|\\.)*")\.length', r"\1.unicodeScalars.count", result)
    return result


def main(path):
    lines = open(path, encoding="utf-8").read().split("\n")
    start = next(i for i, line in enumerate(lines) if line.startswith("fun main()")) + 1
    out = [
        "// Generated by convert_vectors.py from exteraGram's Tools/inline/MathExpressionTests.kt. Do not edit by hand.",
        "",
        "import Foundation",
        "",
        "func runVectorTests() {",
    ]
    documented = False
    for line in lines[start:]:
        text = line.strip()
        if not text or text.startswith("println("):
            continue
        if documented:
            # The table of documented answers; the examples themselves (InlineExamples.kt) belong to the help screen.
            pair = PAIR.match(text)
            if pair:
                out.append("    full(%s, %s, berlin)" % (convert_string(pair.group(1)), convert_string(pair.group(2))))
                continue
            if text == ")":
                break
            if text.startswith(("val berlin", "val documented")):
                continue
            raise SystemExit("unrecognised line: " + text)
        if text.startswith("section("):
            name = STRING.search(text).group(0)[1:-1]
            if name == "documentation examples":
                documented = True
                out.append("    " + convert_line(text))
                out.append('    let berlin = fullOptions(local: TimeZone(identifier: "Europe/Berlin")!)')
                continue
        if text in MANUAL:
            out.extend("    " + swift for swift in MANUAL[text])
            continue
        if not text.startswith(CALLS):
            raise SystemExit("unrecognised line: " + text)
        out.append("    " + convert_line(text))
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
