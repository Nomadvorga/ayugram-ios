# BUILD files, evaluated as Python. Starlark BUILD files are a Python subset; every rule or macro
# this script does not know is a recorder that remembers its keyword arguments.

class Rule(str):
    def __call__(self, *_arguments, **attributes):
        if "name" in attributes and Workspace.loading:
            Workspace.loading[-1][attributes["name"]] = dict(attributes, kind=str(self))
        return Rule(self)

    def __getattr__(self, name: str):  # native.genrule(...), fields of externally loaded structs
        if name.startswith("__"):
            raise AttributeError(name)
        return Rule(name)


class Select:
    def __init__(self, parts: list) -> None:
        self.parts = parts

    def __add__(self, other):
        return Select(self.parts + (other.parts if isinstance(other, Select) else [other]))

    def __radd__(self, other):
        return Select([other] + self.parts)


def flatten(value) -> list:
    """A list attribute with every select() resolved for the iOS arm64 device configuration."""
    if value is None:
        return []
    if not isinstance(value, Select):
        return list(value)
    result: list = []
    for part in value.parts:
        if isinstance(part, dict):
            keys = [key for key in part if key.endswith(":ios_arm64")] or \
                   [key for key in part if key == "//conditions:default"]
            if not keys:
                raise Failure(f"select() without an ios_arm64 or default branch: {sorted(part)}")
            part = part[keys[0]]
        result += flatten(part)
    return result


class Namespace(dict):
    def __missing__(self, key: str):
        if hasattr(builtins, key):
            return getattr(builtins, key)
        return Rule(key)


def parse_label(text: str, package: str) -> tuple[str, str]:
    if text.startswith("//"):
        path, _, name = text[2:].partition(":")
        return path, name or path.rsplit("/", 1)[-1]
    return package, text.lstrip(":")


def is_package(directory: Path) -> bool:
    return any((directory / name).is_file() for name in BUILD_FILE_NAMES)


def glob_pattern(pattern: str) -> re.Pattern:
    expression = ""
    index = 0
    while index < len(pattern):
        if pattern.startswith("**/", index):
            expression += "(?:.*/)?"
            index += 3
        elif pattern.startswith("**", index):
            expression += ".*"
            index += 2
        elif pattern[index] == "*":
            expression += "[^/]*"
            index += 1
        elif pattern[index] == "?":
            expression += "[^/]"
            index += 1
        else:
            expression += re.escape(pattern[index])
            index += 1
    return re.compile(expression + r"\Z")


class Workspace:
    loading: list[dict] = []  # targets of the package being evaluated (macros record into it)

    def __init__(self, root: Path, overlay: Path | None = None) -> None:
        self.root = root
        self.overlay = overlay  # where single files of uninitialized git submodules are fetched to
        self.fetched: list[str] = []
        self.packages: dict[str, dict | None] = {}
        self.lock = threading.RLock()
        self._listings: dict[str, list[str]] = {}
        self._submodules: dict[str, str] | None = None
        self._commits: dict[str, str | None] = {}

    # ----- uninitialized git submodules: single files are read from the pinned commit on GitHub

    def submodules(self) -> dict[str, str]:
        """Path -> URL of every git submodule that is not checked out."""
        if self._submodules is None:
            modules = self.root / ".gitmodules"
            text = modules.read_text(encoding="utf-8") if modules.is_file() else ""
            self._submodules = {}
            for block in re.split(r"^\[submodule ", text, flags=re.M)[1:]:
                path = re.search(r"^\s*path\s*=\s*(\S+)", block, re.M)
                url = re.search(r"^\s*url\s*=\s*(\S+)", block, re.M)
                directory = self.root / path.group(1) if path else None
                if directory is not None and not (directory.is_dir() and any(directory.iterdir())):
                    self._submodules[path.group(1)] = url.group(1) if url else ""
        return self._submodules

    def submodule_location(self, relative: str) -> tuple[Path, str, str] | None:
        """(overlay directory, raw URL prefix, submodule) for a path inside an uninitialized submodule."""
        if self.overlay is None:
            return None
        for submodule, url in self.submodules().items():
            if not (relative + "/").startswith(submodule + "/"):
                continue
            if submodule not in self._commits:
                listed = subprocess.run(["git", "-C", str(self.root), "ls-tree", "HEAD", "--", submodule],
                                        text=True, capture_output=True).stdout
                commit = re.match(r"160000 commit ([0-9a-f]{40})", listed)
                self._commits[submodule] = commit.group(1) if commit else None
            repository = re.match(r"https://github\.com/([^/]+/[^/]+?)(?:\.git)?/?$", url)
            commit = self._commits[submodule]
            if repository is None or commit is None:
                return None
            return (self.overlay / submodule.replace("/", "__") / commit,
                    f"https://raw.githubusercontent.com/{repository.group(1)}/{commit}", submodule)
        return None

    def locate(self, relative: str) -> Path | None:
        """A file of the repository, or of an uninitialized submodule (fetched once into the cache)."""
        path = self.root / relative
        if path.is_file():
            return path
        location = self.submodule_location(relative)
        if location is None:
            return None
        directory, prefix, submodule = location
        rest = relative[len(submodule) + 1:]
        if not rest:
            return None
        target = directory / rest
        absent = target.with_name(target.name + ".absent")
        if target.is_file():
            return target
        if absent.exists():
            return None
        source = f"{prefix}/{urllib.parse.quote(rest)}"
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            with urllib.request.urlopen(source, timeout=60) as response:
                data = response.read()
        except urllib.error.HTTPError as error:
            if error.code == 404:
                absent.touch()
                return None
            raise Failure(f"cannot fetch {source}: {error}")
        except OSError as error:
            raise Failure(f"cannot fetch {source}: {error}")
        partial = target.with_name(f"{target.name}.{os.getpid()}.partial")
        partial.write_bytes(data)
        os.replace(partial, target)
        self.fetched.append(source)
        print(f"FETCH   {source} (single file of uninitialized submodule {submodule})", flush=True)
        return target

    def overlay_directory(self, package: str) -> Path | None:
        location = self.submodule_location(package)
        if location is None:
            return None
        return location[0] / package[len(location[2]) + 1:] if package != location[2] else location[0]

    def listing(self, package: str) -> list[str]:
        """Files of a package, relative to it, not descending into sub-packages (Bazel's glob rule)."""
        if package not in self._listings:
            base = self.root / package
            files = []
            for directory, names, filenames in os.walk(base, followlinks=True):
                current = Path(directory)
                names[:] = sorted(name for name in names if not is_package(current / name))
                prefix = current.relative_to(base).as_posix()
                files += [name if prefix == "." else f"{prefix}/{name}" for name in sorted(filenames)]
            self._listings[package] = files
        return self._listings[package]

    def glob(self, package: str, include, exclude=()) -> list[str]:
        excluded = [glob_pattern(pattern) for pattern in exclude]
        result = []
        for pattern in include:
            expression = glob_pattern(pattern)
            result += [name for name in self.listing(package)
                       if expression.match(name) and not any(other.match(name) for other in excluded)]
        return sorted(dict.fromkeys(result))

    def namespace(self, package: str, origin: str | None = None) -> Namespace:
        """Globals for a BUILD file of `package`, or for a .bzl file in `origin` loaded on its behalf."""
        namespace = Namespace()

        def load(label: str, *names: str, **aliases: str) -> None:
            wanted = dict({name: name for name in names}, **aliases)
            if label.startswith("@"):
                # Rules of external repositories, and build_configuration variables (those are only
                # used in copts of Objective-C sources, which are never compiled here).
                namespace.update({alias: Rule(name) for alias, name in wanted.items()})
                return
            source = parse_label(label, package if origin is None else origin)
            path = self.locate("/".join(source))
            if path is None:
                raise Unobtainable(f"//{source[0]}:{source[1]} cannot be loaded{self.submodule_hint(source[0])}")
            loaded = self.namespace(package, source[0])
            exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), loaded)
            namespace.update({alias: loaded[name] for alias, name in wanted.items()})

        namespace.update(
            load=load,
            glob=lambda include, exclude=(), **_options: self.glob(package, include, exclude),
            select=lambda branches, **_options: Select([branches]),
            package_name=lambda: package,
        )
        return namespace

    def package(self, package: str) -> dict:
        with self.lock:  # one BUILD file is evaluated at a time: `loading` is shared
            if package not in self.packages:
                self.packages[package] = None
                for name in BUILD_FILE_NAMES:
                    path = self.locate(f"{package}/{name}")
                    if path is not None:
                        targets: dict = {}
                        Workspace.loading.append(targets)
                        try:
                            exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"),
                                 self.namespace(package))
                        except Failure:
                            raise
                        except Exception as error:
                            raise Failure(f"cannot evaluate {path}: {type(error).__name__}: {error}")
                        finally:
                            Workspace.loading.pop()
                        self.packages[package] = targets
                        break
            targets = self.packages[package]
        if targets is None:
            raise Unobtainable(f"//{package} has no BUILD file{self.submodule_hint(package)}")
        return targets

    def target(self, package: str, name: str) -> dict:
        targets = self.package(package)
        if name not in targets:
            raise Unobtainable(f"//{package}:{name} is not declared{self.submodule_hint(package + '/' + name)}")
        return targets[name]

    def output_owner(self, package: str, name: str) -> str | None:
        for target_name, target in self.package(package).items():
            if target["kind"] == "genrule" and name in flatten(target.get("outs")):
                return target_name
        return None

    def submodule_hint(self, path: str) -> str:
        """Names the uninitialized git submodule a missing path belongs to, if any."""
        for submodule in self.submodules():
            if (path + "/").startswith(submodule + "/") or (submodule + "/").startswith(path + "/"):
                return f" (git submodule {submodule} is not initialized)"
        return ""

    def resolve(self, text: str) -> tuple[str, str]:
        """A label, a package path or a bare module name given on the command line."""
        if text.startswith("//"):
            return parse_label(text, "")
        candidates = [text] + [f"{prefix}/{text}" for prefix in ("submodules", "AyuGram", "third-party")]
        found = [candidate for candidate in candidates if is_package(self.root / candidate)]
        if not found:
            for directory, names, _files in os.walk(self.root):
                names[:] = [name for name in names if not name.startswith((".", "bazel-"))]
                if Path(directory).name == text and is_package(Path(directory)):
                    found.append(Path(directory).relative_to(self.root).as_posix())
        if len(found) != 1:
            raise Failure(f"{text}: {'no package found' if not found else 'ambiguous: ' + ', '.join(found)}")
        return parse_label("//" + found[0], "")


