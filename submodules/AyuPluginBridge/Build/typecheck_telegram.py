_file_digests: dict[Path, str] = {}


def file_digest(path: Path) -> str:
    if path not in _file_digests:
        _file_digests[path] = hashlib.sha256(path.read_bytes()).hexdigest()
    return _file_digests[path]


def unchanged(paths: list[Path]) -> bool:
    """Whether the files still have the content that was hashed (other agents edit the tree)."""
    stable = True
    for path in paths:
        before = _file_digests.pop(path, None)
        try:
            stable = file_digest(path) == before and stable
        except OSError:
            stable = False
    return stable


def digest(*parts) -> str:
    return hashlib.sha256(json.dumps(parts, sort_keys=True, default=str).encode()).hexdigest()[:20]


def call_labels(name: str, text: str) -> set[tuple[str, ...]]:
    """Argument labels of every `name(...)` call in the text (initializers a placeholder must accept)."""
    result = set()
    for match in re.finditer(r"(?<![\w.])%s\(" % re.escape(name), text):
        index, depth, arguments = match.end(), 1, [""]
        while index < len(text) and depth:
            character = text[index]
            if character in "([{":
                depth += 1
            elif character in ")]}":
                depth -= 1
            if depth == 1 and character == ",":
                arguments.append("")
            elif depth:
                arguments[-1] += character
            index += 1
        labels = []
        for argument in arguments:
            if argument.strip():
                label = re.match(r"\s*(\w+)\s*:", argument)
                labels.append(label.group(1) if label else "_")
        if labels:
            result.add(tuple(labels))
    return result


def stub_source(names: dict[str, str], importer_text: str) -> str:
    """Swift source of a placeholder module: the names its importer needs, nothing real behind them."""
    lines = ["// Placeholder generated by typecheck_telegram.py: the real module cannot be produced on this",
             "// machine. Only the names its importer refers to exist; no member or signature is real."]
    for name, kind in sorted(names.items()):
        if kind == "protocol":
            lines.append(f"public protocol {name} {{}}")
            continue
        lines += [f"public struct {name}: Hashable, Sendable {{", "    public init() {}"]
        for labels in sorted(call_labels(name, importer_text)):
            generics = ", ".join(f"T{index}" for index in range(len(labels)))
            parameters = ", ".join(f"{label} p{index}: T{index}" for index, label in enumerate(labels))
            lines.append(f"    public init<{generics}>({parameters}) {{}}")
        lines.append("}")
    return "\n".join(lines) + "\n"


class Library:
    """A prepared dependency: what a dependent swiftc invocation needs to import it."""

    def __init__(self, label: str, name: str, key: str) -> None:
        self.label = label
        self.name = name
        self.key = key
        self.search: dict[str, None] = {}  # directories holding .swiftmodule files (transitive)
        self.clang: dict[tuple[str, ...], None] = {}  # -Xcc argument groups (transitive)

    def absorb(self, other: "Library") -> None:
        self.search.update(other.search)
        self.clang.update(other.clang)

    def arguments(self) -> list[str]:
        result = [argument for directory in self.search for argument in ("-I", directory)]
        return result + [argument for group in self.clang for argument in group]


class Builder:
    def __init__(self, toolchain: Toolchain, cache: Path, configuration: str, jobs: int, fetch: bool = True) -> None:
        if re.search(r"\s", str(cache)):
            raise Failure(f"the cache path must not contain whitespace: {cache}")
        self.toolchain = toolchain
        self.workspace = Workspace(REPO, cache / "submodules" if fetch else None)
        self.cache = cache
        self.configuration = configuration
        self.jobs = jobs
        self.flavor = [toolchain.version, TARGET, configuration]
        self.libraries: dict[tuple[str, str], Library | None] = {}
        self.generated: dict[tuple[str, str], Path] = {}
        self.tools: dict[tuple[str, str], tuple[Path, str]] = {}
        self.skipped: dict[str, str] = {}  # dependency label -> why it contributes nothing
        self.failures: dict[tuple[str, str], Failure] = {}
        self.stubbed: dict[str, dict] = {}  # placeholder module name -> label, reason, importer, names
        self.unchecked = False
        self.thread = threading.local()
        for name in ("modules", "clang", "generated", "tools", "downloads", "checks", "locks", "tmp",
                     "clang-module-cache"):
            (cache / name).mkdir(parents=True, exist_ok=True)
        self.sweep_temporaries()

    # ----- small helpers

    @staticmethod
    def log(message: str) -> None:
        print(message, flush=True)

    def sweep_temporaries(self) -> None:
        """Remove scratch directories of runs that died (their owning process is gone)."""
        for entry in (self.cache / "tmp").iterdir():
            pid = entry.name.split("-", 1)[0]
            if pid.isdigit():
                try:
                    os.kill(int(pid), 0)
                except ProcessLookupError:
                    shutil.rmtree(entry, ignore_errors=True)
                except PermissionError:
                    pass

    def temporary(self, name: str) -> Path:
        path = self.cache / "tmp" / f"{os.getpid()}-{name}-{time.monotonic_ns()}"
        path.mkdir(parents=True)
        return path

    @contextlib.contextmanager
    def locked(self, name: str):
        """Serializes one cache entry between concurrent runs of this script."""
        with open(self.cache / "locks" / f"{name}.lock", "w") as handle:
            fcntl.flock(handle, fcntl.LOCK_EX)
            try:
                yield
            finally:
                fcntl.flock(handle, fcntl.LOCK_UN)

    @staticmethod
    def prune(final: Path) -> None:
        """Keep the most recently used variants beside a cache entry, drop the rest."""
        siblings = sorted((entry for entry in final.parent.iterdir() if entry != final),
                          key=lambda entry: entry.stat().st_mtime, reverse=True)
        for stale in siblings[KEPT_VERSIONS - 1:]:
            if stale.is_dir():
                shutil.rmtree(stale, ignore_errors=True)
            else:
                stale.unlink(missing_ok=True)

    def publish(self, scratch: Path, final: Path) -> None:
        """Move a finished scratch directory into the cache (a concurrent run may have won)."""
        final.parent.mkdir(parents=True, exist_ok=True)
        try:
            os.replace(scratch, final)
        except OSError:
            shutil.rmtree(scratch, ignore_errors=True)
            if not final.exists():
                raise
        self.prune(final)

    @staticmethod
    def touch(path: Path) -> None:
        with contextlib.suppress(OSError):
            os.utime(path)

    @staticmethod
    def source_key(paths: list[Path]) -> list[tuple[str, str]]:
        result = []
        for path in paths:
            try:
                shown = path.relative_to(REPO).as_posix()
            except ValueError:
                shown = path.name  # generated or downloaded: the content is what matters
            result.append((shown, file_digest(path)))
        return result

    @staticmethod
    def write_list(path: Path, sources: list[Path], quoted: bool = True) -> None:
        path.write_text("".join(f'"{source}"\n' if quoted else f"{source}\n" for source in sources),
                        encoding="utf-8")

    # ----- files behind a srcs/hdrs/tools entry

    def files(self, package: str, entry: str) -> list[Path]:
        if entry.startswith("@"):
            return [self.external_file(entry)]
        target_package, name = parse_label(entry, package)
        if name not in self.workspace.package(target_package):
            path = self.workspace.locate(f"{target_package}/{name}")
            if path is not None:
                return [path]
            owner = self.workspace.output_owner(target_package, name)
            if owner is not None:
                return [self.genrule(target_package, owner) / name]
            raise Unobtainable(f"//{target_package}:{name} is neither a file nor a target"
                               f"{self.workspace.submodule_hint(target_package + '/' + name)}")
        target = self.workspace.target(target_package, name)
        if target["kind"] == "filegroup":
            return [path for source in flatten(target.get("srcs")) for path in self.files(target_package, source)]
        if target["kind"] == "genrule":
            directory = self.genrule(target_package, name)
            return [directory / output for output in flatten(target.get("outs"))]
        raise Unobtainable(f"//{target_package}:{name} ({target['kind']}) cannot be produced here")

    def external_file(self, label: str) -> Path:
        """`@name//file` of an http_file in MODULE.bazel: downloaded once, sha256 verified."""
        name = label[1:].split("//", 1)[0]
        text = (REPO / "MODULE.bazel").read_text(encoding="utf-8")
        match = re.search(r"http_file\(\s*name\s*=\s*\"%s\"(.*?)\n\)" % re.escape(name), text, re.S)
        checksum = match and re.search(r"sha256\s*=\s*\"([0-9a-f]{64})\"", match.group(1))
        url = match and re.search(r"urls\s*=\s*\[\s*\"([^\"]+)\"", match.group(1))
        if not (checksum and url):
            raise Unobtainable(f"{label}: only http_file repositories of MODULE.bazel are supported")
        path = self.cache / "downloads" / checksum.group(1) / "downloaded"
        with self.locked("download-" + name):
            if not path.is_file():
                self.log(f"download {url.group(1)}")
                path.parent.mkdir(parents=True, exist_ok=True)
                partial = path.with_name(f"partial-{os.getpid()}")
                try:
                    with urllib.request.urlopen(url.group(1), timeout=120) as response, \
                            open(partial, "wb") as output:
                        shutil.copyfileobj(response, output)
                except OSError as error:
                    partial.unlink(missing_ok=True)
                    raise Failure(f"{label}: download of {url.group(1)} failed: {error}")
                actual = file_digest(partial)
                if actual != checksum.group(1):
                    partial.unlink()
                    raise Failure(f"{label}: sha256 {actual} does not match MODULE.bazel")
                os.replace(partial, path)
        _file_digests[path] = checksum.group(1)
        return path

    # ----- host tools and genrules

    def tool(self, package: str, entry: str) -> tuple[Path, str]:
        """A genrule tool as (executable, key). swift_binary targets are compiled for the Mac."""
        if entry.startswith("@"):
            path = self.external_file(entry)
            return path, file_digest(path)
        target_package, name = parse_label(entry, package)
        target = self.workspace.package(target_package).get(name)
        if target is None or target["kind"] != "swift_binary":
            (path,) = self.files(package, entry)
            return path, file_digest(path)
        if flatten(target.get("deps")):
            # Only WidgetIDL today; it generates C++ that no Swift module sees.
            raise Unobtainable(f"host tool //{target_package}:{name} has library dependencies and is not built here")
        if (target_package, name) not in self.tools:
            sources = [path for source in flatten(target.get("srcs")) for path in self.files(target_package, source)]
            arguments = ["-O", "-module-name", target.get("module_name", name), *flatten(target.get("copts")),
                         *flatten(target.get("linkopts"))]
            key = digest("tool", self.toolchain.version, arguments, self.source_key(sources))
            final = self.cache / "tools" / name / key
            with self.locked("tool-" + name):
                if not (final / name).is_file():
                    started = time.monotonic()
                    scratch = self.temporary(name)
                    self.write_list(scratch / "sources.rsp", sources)
                    result = self.toolchain.xcrun(["--sdk", "macosx", "swiftc", *arguments,
                                                   f"@{scratch / 'sources.rsp'}", "-o", str(scratch / name)],
                                                  cwd=scratch)
                    if result.returncode != 0:
                        shutil.rmtree(scratch, ignore_errors=True)
                        raise Failure(f"host tool //{target_package}:{name} failed to build:\n{result.stdout}")
                    for leftover in scratch.iterdir():
                        if leftover.name != name:
                            leftover.unlink()
                    self.publish(scratch, final)
                    self.log(f"tool    //{target_package}:{name}: built for the Mac "
                             f"({time.monotonic() - started:.0f}s)")
            self.touch(final)
            self.tools[(target_package, name)] = (final / name, key)
        return self.tools[(target_package, name)]

    def genrule(self, package: str, name: str) -> Path:
        """Run a genrule once per input hash; returns the directory that holds its outs."""
        if (package, name) in self.generated:
            return self.generated[(package, name)]
        target = self.workspace.target(package, name)
        outputs = flatten(target.get("outs"))
        if any(output.endswith(NATIVE_OUTPUTS) for output in outputs):
            raise NativeBuild(f"genrule //{package}:{name} builds native code and is never run here")
        tools = {entry: self.tool(package, entry) for entry in flatten(target.get("tools"))}
        sources = {entry: self.files(package, entry) for entry in flatten(target.get("srcs"))}
        command = target.get("cmd_bash") or target.get("cmd")
        if not isinstance(command, str) or isinstance(command, Rule):
            raise Failure(f"genrule //{package}:{name} has no usable cmd")
        key = digest("genrule", command, outputs,
                     [(entry, self.source_key(paths)) for entry, paths in sources.items()],
                     [(entry, tool_key) for entry, (_path, tool_key) in tools.items()])
        final = self.cache / "generated" / f"{package}/{name}".replace("/", "__") / key
        with self.locked("genrule-" + f"{package}/{name}".replace("/", "__")):
            if not all((final / output).is_file() for output in outputs):
                started = time.monotonic()
                # Like Bazel, the command runs in a scratch root and sees paths relative to it
                # (the FlatSerialization rule prefixes one with $(pwd)).
                work = self.temporary(name)
                scratch = work / "out"

                def relative(path: Path) -> str:
                    return os.path.relpath(path, work)

                def locate(label: str) -> list[Path]:
                    if label in outputs:
                        return [scratch / label]
                    if label in tools:
                        return [tools[label][0]]
                    return sources[label] if label in sources else self.files(package, label)

                def expand(match: re.Match) -> str:
                    token = match.group(0)
                    if token == "$$":
                        return "$"
                    if token == "$@":
                        return relative(scratch / outputs[0])
                    if token == "$<":
                        return " ".join(relative(path) for paths in sources.values() for path in paths)
                    word, _, argument = match.group(1).strip().partition(" ")
                    if word in ("location", "locations", "execpath", "execpaths", "rootpath", "rootpaths"):
                        return " ".join(relative(path) for path in locate(argument.strip()))
                    if word in ("RULEDIR", "@D"):
                        return relative(scratch)
                    if word == "OUTS":
                        return " ".join(relative(scratch / output) for output in outputs)
                    if word == "SRCS":
                        return " ".join(relative(path) for paths in sources.values() for path in paths)
                    raise Failure(f"genrule //{package}:{name}: make variable {token} is not supported")

                script = re.sub(r"\$\$|\$\(([^()]*)\)|\$[@<]", expand, command)
                for output in outputs:
                    (scratch / output).parent.mkdir(parents=True, exist_ok=True)
                self.log(f"genrule //{package}:{name}: running")
                result = subprocess.run(["/bin/bash", "-c", "set -euo pipefail\n" + script], cwd=work,
                                        env=self.toolchain.environment, text=True, errors="replace",
                                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
                missing = [output for output in outputs if not (scratch / output).is_file()]
                if result.returncode != 0 or missing:
                    shutil.rmtree(work, ignore_errors=True)
                    raise Failure(f"genrule //{package}:{name} failed (exit {result.returncode}, missing outputs "
                                  f"{missing}):\n{result.stdout[-6000:]}")
                # Keep only the declared outputs (the flatc rule leaves a CMake and a build tree behind).
                kept = {scratch / output for output in outputs}
                for directory, names, filenames in os.walk(scratch, topdown=False):
                    for filename in filenames:
                        if Path(directory) / filename not in kept:
                            (Path(directory) / filename).unlink()
                    for child in names:
                        child_path = Path(directory) / child
                        if child_path.is_symlink():
                            child_path.unlink()
                        else:
                            with contextlib.suppress(OSError):
                                child_path.rmdir()
                self.publish(scratch, final)
                shutil.rmtree(work, ignore_errors=True)
                self.log(f"genrule //{package}:{name}: {len(outputs)} outputs ({time.monotonic() - started:.0f}s)")
        self.touch(final)
        self.generated[(package, name)] = final
        return final

    # ----- dependencies

    def library(self, package: str, name: str) -> Library | None:
        """Prepare //package:name as an importable dependency (None: it has no Swift-visible part)."""
        identity = (package, name)
        if identity in self.libraries:
            return self.libraries[identity]
        if identity in self.failures:
            raise self.failures[identity]
        in_progress = self.thread.__dict__.setdefault("in_progress", [])
        if identity in in_progress:
            raise Failure(f"dependency cycle through //{package}:{name}")
        in_progress.append(identity)
        try:
            target = self.workspace.target(package, name)
            if target["kind"] in SWIFT_KINDS:
                library = self.swift_interface(package, name, target)
            elif target["kind"] in CLANG_KINDS:
                try:
                    library = self.clang_module(package, name, target)
                except Unobtainable as reason:
                    # Its headers are build products or live in an uninitialized submodule. Swift
                    # rarely sees them (they sit behind an Objective-C wrapper); if a module does
                    # need them, its import fails loudly.
                    self.skipped[f"//{package}:{name}"] = f"headers unavailable: {reason}"
                    library = None
            elif target["kind"] in FRAMEWORK_KINDS:
                library = self.framework(package, name, target)
            else:
                self.skipped[f"//{package}:{name}"] = f"{target['kind']} has no Swift-visible interface"
                library = None
        except Failure as reason:
            self.failures[identity] = reason
            raise
        finally:
            in_progress.pop()
        self.libraries[identity] = library
        return library

    def prepare(self, roots: list[tuple[str, str]]) -> None:
        """Prepare a dependency closure bottom-up with several compilers at once. Failures are kept
        and raised when the dependency is requested for real."""
        graph: dict[tuple[str, str], list[tuple[str, str]]] = {}
        pending = list(roots)
        while pending:
            identity = pending.pop()
            if identity in graph:
                continue
            graph[identity] = []
            try:
                target = self.workspace.target(*identity)
            except Failure:
                continue
            if target["kind"] in (*SWIFT_KINDS, *CLANG_KINDS):
                graph[identity] = [parse_label(entry, identity[0]) for entry in flatten(target.get("deps"))
                                   if not entry.startswith("@")]
                pending += graph[identity]
        depth: dict[tuple[str, str], int] = {}
        order = list(graph)
        while order:  # iterative longest-path depth; a cycle is left to library() to report
            identity = order.pop()
            waiting = [edge for edge in graph[identity] if edge not in depth and edge != identity]
            if waiting and len(order) < 4 * len(graph):
                order += [identity, *waiting]
            elif identity not in depth:
                depth[identity] = 1 + max((depth.get(edge, 0) for edge in graph[identity]), default=0)
        todo = [identity for identity in graph if identity not in self.libraries and identity not in self.failures]
        if len(todo) < 2:
            return

        def attempt(identity: tuple[str, str]) -> None:
            with contextlib.suppress(Failure):
                self.library(*identity)

        with concurrent.futures.ThreadPoolExecutor(max_workers=self.jobs) as pool:
            for level in sorted({depth[identity] for identity in todo}):
                list(pool.map(attempt, [identity for identity in todo if depth[identity] == level]))

    def dependencies(self, package: str, target: dict) -> tuple[list[Library], list[tuple[str, str | None, str]]]:
        """Prepared deps, and (label, module name, reason) of Swift or Clang deps that cannot be produced."""
        result, missing = [], []
        for entry in flatten(target.get("deps")):
            if entry.startswith("@"):
                self.skipped[entry] = "external repository"
                continue
            identity = parse_label(entry, package)
            try:
                library = self.library(*identity)
            except Unobtainable as reason:
                try:
                    module = self.workspace.target(*identity).get("module_name")
                except Unobtainable:
                    module = None
                missing.append((f"//{identity[0]}:{identity[1]}", module, str(reason)))
                continue
            if library is not None:
                result.append(library)
        return result, missing

    def framework(self, package: str, name: str, target: dict) -> Library:
        """A prebuilt (xc)framework: its iOS arm64 slice goes on the framework search path."""
        entries = flatten(target.get("xcframework_imports")) + flatten(target.get("framework_imports"))
        directories: dict[str, None] = {}
        interface = []
        for entry in entries:
            match = re.match(r"(?:(.*)/)?[^/]+\.framework/", entry)
            if match is None:
                continue
            parent = match.group(1) or ""
            if ".xcframework" in parent and not re.match(r"ios-arm64(?!.*(?:simulator|maccatalyst))",
                                                         parent.rsplit("/", 1)[-1]):
                continue
            directories[os.path.normpath(REPO / package / parent)] = None
            if entry.endswith((".h", ".modulemap", ".swiftinterface")):
                interface.append(REPO / package / entry)
        library = Library(f"//{package}:{name}", name, digest("framework", self.source_key(interface)))
        for directory in directories:
            library.clang[("-F", directory)] = None
        return library

    def clang_module(self, package: str, name: str, target: dict) -> Library:
        """Module map over the public headers of an objc_library/cc_library; nothing is compiled."""
        module = target.get("module_name") or re.sub(r"[^A-Za-z0-9_]", "_", f"{package}_{name}")
        headers = [path for entry in flatten(target.get("hdrs")) for path in self.files(package, entry)]
        headers = [path for path in headers if path.suffix in HEADER_SUFFIXES]
        textual = [path for entry in flatten(target.get("textual_hdrs")) for path in self.files(package, entry)]
        includes = [os.path.normpath(REPO / package / include) for include in flatten(target.get("includes"))]
        roots = [directory for (owner, _name), directory in self.generated.items() if owner == package]
        roots += [directory for directory in [self.workspace.overlay_directory(package)] if directory]
        for root in roots:  # `includes` also apply to generated headers and to fetched submodule files
            includes += [str(root / include) for include in flatten(target.get("includes"))
                         if (root / include).is_dir()]
        defines = flatten(target.get("defines"))
        dependencies, missing = self.dependencies(package, target)
        for label, _module, reason in missing:
            self.skipped[label] = f"headers unavailable: {reason}"
        key = digest("clang", module, flatten(target.get("includes")), defines, self.source_key(headers),
                     self.source_key(textual), [dependency.key for dependency in dependencies])
        library = Library(f"//{package}:{name}", module, key)
        if headers or textual:
            directory = self.cache / "clang" / module / key
            if not (directory / "module.modulemap").is_file():
                scratch = self.temporary(module)
                lines = [f'module "{module}" {{', "    export *"]
                lines += [f'    header "{path}"' for path in headers]
                lines += [f'    textual header "{path}"' for path in textual]
                (scratch / "module.modulemap").write_text("\n".join(lines) + "\n}\n", encoding="utf-8")
                self.publish(scratch, directory)
            self.touch(directory)
            library.clang[("-Xcc", f"-fmodule-map-file={directory / 'module.modulemap'}")] = None
        for include in includes:
            library.clang[("-Xcc", f"-I{include}")] = None
        for define in defines:
            library.clang[("-Xcc", f"-D{define}")] = None
        for dependency in dependencies:
            library.absorb(dependency)
        return library

    def swift_inputs(self, package: str, name: str, target: dict):
        """Module name, Swift sources, the target's own flags, its prepared dependencies, and the
        (label, module name, reason) of every dependency that cannot be produced on this machine."""
        module = target.get("module_name") or re.sub(r"[^A-Za-z0-9_]", "_", f"{package}_{name}")
        if target["kind"] == "swift_intent_library":
            sources = self.intent_sources(package, name, target)
        else:
            sources = [path for entry in flatten(target.get("srcs")) for path in self.files(package, entry)]
        sources = [path for path in dict.fromkeys(sources) if path.suffix == ".swift"]
        options = list(flatten(target.get("copts"))) + [f"-D{define}" for define in flatten(target.get("defines"))]
        dependencies, missing = self.dependencies(package, target)
        combined = Library(f"//{package}:{name}", module, digest([dependency.key for dependency in dependencies]))
        for dependency in dependencies:
            combined.absorb(dependency)
        return module, sources, options, combined, missing

    def intent_sources(self, package: str, name: str, target: dict) -> list[Path]:
        """swift_intent_library: Swift classes generated from an .intentdefinition by intentbuilderc."""
        (definition,) = self.files(package, target["src"])
        arguments = ["-classPrefix", target.get("class_prefix", ""), "-language", "Swift",
                     "-swiftVersion", str(target.get("swift_version", "5"))]
        key = digest("intents", self.toolchain.version, arguments, self.source_key([definition]))
        final = self.cache / "generated" / f"{package}/{name}".replace("/", "__") / key
        with self.locked("genrule-" + f"{package}/{name}".replace("/", "__")):
            if not final.is_dir():
                scratch = self.temporary(name)
                result = self.toolchain.xcrun(["intentbuilderc", "generate", "-input", str(definition),
                                               "-output", str(scratch), *arguments], cwd=scratch)
                if result.returncode != 0 or not any(scratch.glob("*.swift")):
                    shutil.rmtree(scratch, ignore_errors=True)
                    raise Failure(f"intentbuilderc failed for //{package}:{name}:\n{result.stdout}")
                self.publish(scratch, final)
                self.log(f"intents //{package}:{name}: generated")
        self.touch(final)
        return sorted(final.glob("*.swift"))

    def common_arguments(self) -> list[str]:
        # What rules_swift passes for an iOS swift_library that matters to the type checker.
        # `-c opt` (CI builds release_arm64) defines NDEBUG, `-c dbg` defines DEBUG.
        return ["-sdk", self.toolchain.sdk("iphoneos"), "-target", TARGET, "-swift-version", "5",
                "-parse-as-library", "-enforce-exclusivity=checked",
                # Like rules_swift; it also keeps search paths out of the .swiftmodule, so that the
                # file depends only on the declarations (see module_key).
                "-Xfrontend", "-no-serialize-debugging-options",
                "-DDEBUG" if self.configuration == "debug" else "-DNDEBUG",
                "-module-cache-path", str(self.cache / "clang-module-cache"),
                "-Xcc", f"-iquote{REPO}"]

    def interface_directory(self, module: str, sources: list[Path], options: list[str], imports: Library,
                            stubs: list[str] | None = None) -> Path:
        options = [option for option in options if option not in ("-warnings-as-errors", "-suppress-warnings")]
        key = digest("swift-interface", self.flavor, module, options, self.source_key(sources), imports.key,
                     *([["placeholders", STUB_ROUNDS, sorted(stubs)]] if stubs else []))
        return self.cache / "modules" / module / key

    def swift_interface(self, package: str, name: str, target: dict) -> Library:
        """`swiftc -emit-module` of a dependency: declarations only, bodies are not type-checked."""
        module, sources, options, imports, missing = self.swift_inputs(package, name, target)
        stubs: dict[str, tuple[str, str]] = {}
        for label, stub_module, reason in missing:
            if stub_module is None:
                raise Failure(f"{label}, a dependency of //{package}:{name}, cannot be produced here and its "
                              f"module name is unknown: {reason}")
            stubs[stub_module] = (label, reason)
        directory = self.interface_directory(module, sources, options, imports, list(stubs))
        if not (directory / f"{module}.swiftmodule").is_file():
            with self.locked("module-" + module):
                if not (directory / f"{module}.swiftmodule").is_file():
                    started = time.monotonic()
                    scratch = self.temporary(module)
                    self.write_list(scratch / "sources.rsp", sources)
                    options = [option for option in options if option != "-warnings-as-errors"]
                    command = [
                        "swiftc", "-emit-module", "-wmo", *(SKIP_ALL_BODIES if stubs else SKIP_BODIES),
                        "-suppress-warnings", "-module-name", module, *self.common_arguments(), *options,
                        *imports.arguments(), *(["-I", str(scratch)] if stubs else []),
                        "-emit-module-path", str(scratch / f"{module}.swiftmodule"),
                        f"@{scratch / 'sources.rsp'}"]
                    try:
                        if stubs:
                            self.compile_with_placeholders(module, stubs, sources, command, scratch)
                        else:
                            result = self.toolchain.xcrun(command, cwd=scratch)
                            if result.returncode != 0:
                                raise Failure(f"dependency module {module} (//{package}:{name}) does not "
                                              f"compile:\n{result.stdout.strip()}")
                        if not unchanged(sources):
                            raise Failure(f"sources of {module} changed while it was compiled; run again")
                    except Failure:
                        shutil.rmtree(scratch, ignore_errors=True)
                        raise
                    kept = {f"{module}.swiftmodule", f"{module}.swiftdoc", "placeholders.json"}
                    kept |= {f"{stub}{suffix}" for stub in stubs for suffix in (".swiftmodule", ".placeholder.swift")}
                    self.publish_module(scratch, directory, kept)
                    self.log(f"module  {module}: {len(sources)} files, declarations only "
                             f"({time.monotonic() - started:.0f}s)")
        self.touch(directory)
        if stubs:
            recorded = json.loads((directory / "placeholders.json").read_text(encoding="utf-8"))
            for stub, (label, reason) in stubs.items():
                known = self.stubbed.get(stub)
                if known is not None and known["importer"] != module:
                    raise Failure(f"placeholder module {stub} is needed by both {known['importer']} and {module}; "
                                  f"only one importer is supported")
                if known is None:
                    self.stubbed[stub] = {"label": label, "reason": reason, "importer": module,
                                          "names": recorded[stub], "source": directory / f"{stub}.placeholder.swift"}
                    self.log(f"PLACEHOLDER module {stub}: {recorded[stub]} names inferred from its only importer "
                             f"{module}; nothing in it is real ({label}: {reason})")
        library = Library(f"//{package}:{name}", module, self.module_key(directory))
        library.search[str(directory)] = None
        library.absorb(imports)
        return library

    @staticmethod
    def module_key(directory: Path) -> str:
        """Hash of the emitted .swiftmodule files. Dependents are keyed by it, not by the sources:
        an edit inside function bodies leaves the declarations-only module byte-identical, and then
        nothing that imports it is rebuilt."""
        stored = directory / "content.key"
        if not stored.is_file():
            content = digest([file_digest(path) for path in sorted(directory.glob("*.swiftmodule"))])
            partial = directory / f"content.key.{os.getpid()}.{threading.get_ident()}"
            partial.write_text(content, encoding="utf-8")
            os.replace(partial, stored)
        return stored.read_text(encoding="utf-8")

    def compile_with_placeholders(self, module: str, stubs: dict[str, tuple[str, str]], sources: list[Path],
                                  command: list[str], scratch: Path) -> None:
        """Emit `module` although the modules in `stubs` cannot be produced: declare, in placeholder
        modules of the same names, exactly the names the compiler misses, until the interface emits."""
        names: dict[str, dict[str, str]] = {stub: {} for stub in stubs}
        first = next(iter(names))
        text = "\n".join(source.read_text(encoding="utf-8", errors="replace") for source in sources)
        output = ""
        for _round in range(STUB_ROUNDS):
            for stub, declared in names.items():
                source = scratch / f"{stub}.placeholder.swift"
                source.write_text(stub_source(declared, text), encoding="utf-8")
                built = self.toolchain.xcrun([
                    "swiftc", "-emit-module", "-module-name", stub, *self.common_arguments(), "-suppress-warnings",
                    "-emit-module-path", str(scratch / f"{stub}.swiftmodule"), str(source)], cwd=scratch)
                if built.returncode != 0:
                    raise Failure(f"placeholder module {stub} for {module} does not compile:\n{built.stdout.strip()}")
            result = self.toolchain.xcrun(command, cwd=scratch)
            if result.returncode == 0:
                (scratch / "placeholders.json").write_text(
                    json.dumps({stub: len(declared) for stub, declared in names.items()}), encoding="utf-8")
                return
            output = result.stdout
            progress = False
            for found in re.findall(r"cannot find (?:type )?'([A-Z]\w*)' in scope", output):
                if not any(found in declared for declared in names.values()):
                    names[first][found] = "struct"
                    progress = True
            for found, owner in re.findall(r"no type named '(\w+)' in module '(\w+)'", output):
                if owner in names and found not in names[owner]:
                    names[owner][found] = "struct"
                    progress = True
            for found in re.findall(r"inheritance from non-protocol, non-class type '(\w+)'", output):
                for declared in names.values():
                    if declared.get(found) == "struct":
                        declared[found] = "protocol"
                        progress = True
            if not progress:
                break
        raise Failure(f"module {module} imports {', '.join(names)}, which cannot be produced on this machine, and "
                      f"placeholder declarations could not be derived:\n{output.strip()[-4000:]}")

    def publish_module(self, scratch: Path, directory: Path, kept: set[str]) -> None:
        for leftover in scratch.iterdir():
            if leftover.name not in kept:
                shutil.rmtree(leftover, ignore_errors=True) if leftover.is_dir() else leftover.unlink()
        self.publish(scratch, directory)

    # ----- checks

    def report(self, label: str, result: subprocess.CompletedProcess, started: float) -> bool:
        # The module-emission job repeats declaration errors that a compile job already printed.
        blocks: list[list[str]] = [[]]
        for line in result.stdout.splitlines():
            if DIAGNOSTIC.match(line) and blocks[-1]:
                blocks.append([])
            blocks[-1].append(line)
        output = "\n\n".join(dict.fromkeys(text for text in ("\n".join(block).strip() for block in blocks) if text))
        if output:
            print(output, flush=True)
        errors = len(re.findall(r"^\S.*:\d+:\d+: error: ", output, re.M))
        state = "ok" if result.returncode == 0 else f"FAILED ({errors} error{'s' if errors != 1 else ''})"
        self.log(f"check   {label}: {state} ({time.monotonic() - started:.0f}s)")
        return result.returncode == 0

    def check_module(self, package: str, name: str, extra: list[str], primary: list[str], recheck: bool,
                     substitute: list[str] | None = None) -> bool:
        """Type-check every body of a swift_library with its own copts (or only the primary files)."""
        target = self.workspace.target(package, name)
        if target["kind"] != "swift_library":
            raise Failure(f"//{package}:{name} is a {target['kind']}, not a swift_library")
        self.prepare([parse_label(entry, package) for entry in flatten(target.get("deps"))
                      if not entry.startswith("@")])
        module, sources, options, imports, missing = self.swift_inputs(package, name, target)
        if missing:
            raise Failure(f"//{package}:{name} depends directly on targets that cannot be produced here: "
                          + "; ".join(f"{label} ({reason})" for label, _module, reason in missing))
        added = [Path(path).resolve() for path in extra]
        missing = [str(path) for path in added if not path.is_file()]
        if missing:
            raise Failure("no such file: " + ", ".join(missing))
        for pair in substitute or []:
            original, _, replacement = pair.partition("=")
            old, new = Path(original).resolve(), Path(replacement).resolve()
            if old not in sources or not new.is_file():
                raise Failure(f"--substitute {pair}: the first must be a source of {module}, the second a file")
            sources[sources.index(old)] = new
            added.append(new)
        sources = list(dict.fromkeys([*sources, *added]))
        arguments = ["-module-name", module, *self.common_arguments(), *options, *imports.arguments()]
        started = time.monotonic()
        if primary:
            return self.check_primary(module, sources, arguments, primary, started)

        key = digest("check", self.flavor, module, options, self.source_key(sources), imports.key)
        stamp = self.cache / "checks" / module / f"{key}.ok"
        if stamp.is_file() and not recheck:
            self.touch(stamp)
            self.log(f"check   {module}: ok, {len(sources)} files unchanged since the last clean check")
            return True
        with self.locked("check-" + module):
            scratch = self.temporary(module)
            self.write_list(scratch / "sources.rsp", sources)
            # Without -wmo the driver type-checks all bodies in parallel batches and runs the SIL
            # diagnostics (definite initialization, missing return, unreachable code), then stops:
            # no object code. The module it emits is the same one a dependent needs.
            result = self.toolchain.xcrun([
                "swiftc", "-emit-module", "-enable-batch-mode", "-j", str(self.jobs),
                "-continue-building-after-errors", *arguments,
                "-emit-module-path", str(scratch / f"{module}.swiftmodule"),
                f"@{scratch / 'sources.rsp'}"], cwd=scratch)
            clean = self.report(f"{module}, {len(sources)} files, all bodies", result, started)
            directory = self.interface_directory(module, sources, options, imports)
            remember = clean and unchanged(sources)
            if remember and not added and (scratch / f"{module}.swiftmodule").is_file() and not directory.exists():
                self.publish_module(scratch, directory, {f"{module}.swiftmodule", f"{module}.swiftdoc"})
            else:
                shutil.rmtree(scratch, ignore_errors=True)
            if remember:
                stamp.parent.mkdir(parents=True, exist_ok=True)
                stamp.write_text(self.toolchain.version + "\n", encoding="utf-8")
                self.prune(stamp)
            elif clean:
                self.log(f"note    sources of {module} changed during the check; the result is not remembered")
        return clean

    def check_primary(self, module: str, sources: list[Path], arguments: list[str], primary: list[str],
                      started: float) -> bool:
        """One frontend job with the given files as primary inputs and the rest of the module as context."""
        wanted = [Path(path).resolve() for path in primary]
        known = {source.resolve() for source in sources}
        unknown = [str(path) for path in wanted if path not in known]
        if unknown:
            raise Failure(f"not sources of module {module} (check the srcs globs of its BUILD file, or pass "
                          f"them with --extra): " + ", ".join(unknown))
        scratch = self.temporary(module + "-primary")
        try:
            # Ask the driver for the frontend command line it would use, then replace the inputs.
            probes = [scratch / "probe_a.swift", scratch / "probe_b.swift"]
            for probe in probes:
                probe.write_text("", encoding="utf-8")
            printed = self.toolchain.xcrun(["swiftc", "-driver-print-jobs", "-emit-module", *arguments,
                                            "-emit-module-path", str(scratch / "probe.swiftmodule"),
                                            *map(str, probes)], cwd=scratch)
            lines = [line for line in printed.stdout.splitlines() if f"-primary-file {probes[0]}" in line]
            if printed.returncode != 0 or not lines:
                raise Failure(f"cannot derive the frontend command line:\n{printed.stdout[-3000:]}")
            command: list[str] = []
            dropped = {"-primary-file", *map(str, probes)}
            tokens = iter(shlex.split(lines[0]))
            for token in tokens:
                if token == "-o":
                    next(tokens)
                elif token not in dropped:
                    command.append(token)
            self.write_list(scratch / "all.txt", sources, quoted=False)
            self.write_list(scratch / "primary.txt", wanted, quoted=False)
            self.write_list(scratch / "outputs.txt",
                            [scratch / f"partial{index}.swiftmodule" for index in range(len(wanted))], quoted=False)
            result = subprocess.run(
                [*command, "-filelist", str(scratch / "all.txt"), "-primary-filelist", str(scratch / "primary.txt"),
                 "-output-filelist", str(scratch / "outputs.txt")],
                env=self.toolchain.environment, cwd=scratch, text=True,
                stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            return self.report(f"{module}, {len(wanted)} primary of {len(sources)} files "
                               f"(errors caused in other files are not reported)", result, started)
        finally:
            shutil.rmtree(scratch, ignore_errors=True)

    def check_files(self, files: list[str], module: str, labels: list[str], explicit: bool) -> bool:
        """Type-check loose files as one module against the cached modules they import."""
        sources = [Path(path).resolve() for path in files]
        missing = [str(path) for path in sources if not path.is_file()]
        if missing:
            raise Failure("no such file: " + ", ".join(missing))
        text = "\n".join(path.read_text(encoding="utf-8", errors="replace") for path in sources)
        imported = set(re.findall(
            r"^[ \t]*(?:@\w+(?:\([^)\n]*\))?[ \t]+)*import[ \t]+(?:(?:struct|class|enum|protocol|func|var|let|"
            r"typealias)[ \t]+)?(\w+)", text, re.M))
        imports = Library("files", module, "")
        wanted = []
        for label in labels:
            package, name = self.workspace.resolve(label)
            target = self.workspace.target(package, name)
            if explicit or target.get("module_name", name) in imported:
                wanted.append((package, name, target))
        self.prepare([(package, name) for package, name, _target in wanted])
        for package, name, target in wanted:
            library = self.library(package, name)
            if library is not None:
                imports.absorb(library)
            visibility = flatten(target.get("visibility"))
            if "//visibility:public" not in visibility:
                self.log(f"note    //{package}:{name} is visible only to {', '.join(visibility) or 'its package'} "
                         f"in Bazel; this check does not enforce that")
        started = time.monotonic()
        scratch = self.temporary(module)
        try:
            # -wmo without the skip flag checks all bodies and runs the SIL diagnostics in one job.
            result = self.toolchain.xcrun([
                "swiftc", "-emit-module", "-wmo", "-module-name", module, *self.common_arguments(),
                "-warnings-as-errors", *imports.arguments(),
                "-emit-module-path", str(scratch / f"{module}.swiftmodule"), *map(str, sources)], cwd=scratch)
            return self.report(f"{module}, {len(sources)} files", result, started)
        finally:
            shutil.rmtree(scratch, ignore_errors=True)

    # ----- plugin wiring outside the bridge module

    def app_files(self) -> tuple[dict[tuple[str, str], list[Path]], list[tuple[Path, str]]]:
        """Swift files outside the bridge module that mention AyuPlugin, by the swift_library that
        compiles them; and the files that no swift_library compiles, with the reason."""
        found = []
        for root in APP_ROOTS:
            for directory, names, filenames in os.walk(REPO / root):
                relative = Path(directory).relative_to(REPO).as_posix()
                names[:] = sorted(name for name in names
                                  if not name.startswith(".") and f"{relative}/{name}" not in APP_EXCLUDED)
                for filename in sorted(filenames):
                    path = Path(directory) / filename
                    if filename.endswith(".swift") and APP_MARKER in path.read_text(encoding="utf-8", errors="replace"):
                        found.append(path)
        build_texts: dict[str, str] | None = None
        owned: dict[tuple[str, str], list[Path]] = {}
        orphans: list[tuple[Path, str]] = []
        for path in found:
            directory = path.parent
            while directory != REPO and not is_package(directory):
                directory = directory.parent
            package = directory.relative_to(REPO).as_posix()
            entry = path.relative_to(directory).as_posix()
            targets = self.workspace.package(package)

            def compiles(target: dict, wanted: tuple[str, str], home: str) -> bool:
                return target["kind"] == "swift_library" and any(
                    parse_label(source, home) == wanted for source in flatten(target.get("srcs"))
                    if not source.startswith("@"))

            owners = [(package, name) for name, target in targets.items() if compiles(target, (package, entry), package)]
            groups = [name for name, target in targets.items()
                      if target["kind"] == "filegroup" and entry in flatten(target.get("srcs"))]
            if groups and not owners:  # a filegroup compiled into a module of another package
                if build_texts is None:
                    build_texts = {}
                    for directory_name, names, filenames in os.walk(REPO):
                        names[:] = [name for name in names if not name.startswith((".", "bazel-"))]
                        for filename in filenames:
                            if filename in BUILD_FILE_NAMES:
                                home = Path(directory_name).relative_to(REPO).as_posix()
                                build_texts[home] = (Path(directory_name) / filename).read_text(
                                    encoding="utf-8", errors="replace")
                for home, text in build_texts.items():
                    if f"//{package}" not in text:
                        continue
                    with contextlib.suppress(Failure):
                        owners += [(home, name) for name, target in self.workspace.package(home).items()
                                   if any(compiles(target, (package, group), home) for group in groups)]
            real = [owner for owner in owners if not self.workspace.target(*owner).get("testonly")]
            if real:
                for owner in real:
                    owned.setdefault(owner, []).append(path)
            else:
                orphans.append((path, "only a test target compiles it" if owners else "no swift_library compiles it"))
        return owned, orphans

    def check_app(self, primary_only: bool, recheck: bool) -> bool:
        """--ayu-app: every module outside the bridge that compiles a file mentioning AyuPlugin gets
        a full check (all bodies of the whole module), or with --primary only those files."""
        owned, orphans = self.app_files()
        clean = True
        unchecked = [f"{path.relative_to(REPO)}: {reason}" for path, reason in orphans]
        for (package, name), paths in sorted(owned.items()):
            self.log(f"--- //{package}:{name}: " + ", ".join(path.name for path in paths))
            try:
                clean = self.check_module(package, name, [], [str(path) for path in paths] if primary_only else [],
                                          recheck) and clean
            except Failure as failure:
                unchecked += [f"{path.relative_to(REPO)}: //{package}:{name} cannot be prepared" for path in paths]
                self.log(f"UNCHECKED //{package}:{name}: {failure}")
        for line in unchecked:
            self.log(f"UNCHECKED {line}")
        self.unchecked = bool(unchecked)
        return clean

    # ----- closure report

    def tool_available(self, package: str, entry: str) -> bool:
        if entry.startswith("@"):
            name = entry[1:].split("//", 1)[0]
            return re.search(r"http_file\(\s*name\s*=\s*\"%s\"" % re.escape(name),
                             (REPO / "MODULE.bazel").read_text(encoding="utf-8")) is not None
        tool_package, name = parse_label(entry, package)
        try:
            target = self.workspace.package(tool_package).get(name)
        except Failure:
            return False
        return target is None or target["kind"] in ("swift_binary", "genrule", "filegroup")

    def closure(self, package: str, name: str) -> bool:
        """Print what preparing //package:name would involve; evaluates BUILD files only."""
        kinds: dict[str, list[str]] = {}
        problems: dict[str, None] = {}
        external: dict[str, None] = {}
        swift = {"files": 0, "bytes": 0}
        seen: set[tuple[str, str]] = set()
        pending = [(package, name)]
        while pending:
            package, name = pending.pop()
            if (package, name) in seen:
                continue
            seen.add((package, name))
            try:
                target = self.workspace.package(package).get(name)
                if target is None:
                    path = self.workspace.locate(f"{package}/{name}")
                    owner = None if path is not None else self.workspace.output_owner(package, name)
                    if owner is not None:
                        pending.append((package, owner))
                    elif path is None:
                        problems[f"//{package}:{name} is neither a file nor a target"
                                 f"{self.workspace.submodule_hint(package + '/' + name)}"] = None
                    elif path.suffix == ".swift":
                        swift["files"] += 1
                        swift["bytes"] += path.stat().st_size
                    continue
                if target["kind"] == "genrule" and any(
                        output.endswith(NATIVE_OUTPUTS) for output in flatten(target.get("outs"))):
                    kinds.setdefault("native-build genrule (never run; headers it produces are unavailable)",
                                     []).append(f"//{package}:{name}")
                    continue
                if target["kind"] == "genrule" and not all(
                        self.tool_available(package, entry) for entry in flatten(target.get("tools"))):
                    kinds.setdefault("genrule whose tools cannot be built here (its outputs are unavailable)",
                                     []).append(f"//{package}:{name}")
                    continue
                kinds.setdefault(target["kind"], []).append(f"//{package}:{name}")
                attributes = {"swift_library": ("deps", "srcs"), "swift_binary": ("deps", "srcs"),
                              "swift_intent_library": ("src",),
                              "objc_library": ("deps", "hdrs", "textual_hdrs"),
                              "cc_library": ("deps", "hdrs", "textual_hdrs"),
                              "filegroup": ("srcs",), "genrule": ("srcs", "tools")}.get(target["kind"], ())
                for attribute in attributes:
                    value = target.get(attribute)
                    for entry in [value] if isinstance(value, str) else flatten(value):
                        if entry.startswith("@"):
                            external[entry] = None
                        else:
                            pending.append(parse_label(entry, package))
            except Failure as failure:
                problems[str(failure)] = None
        self.log("closure:")
        for kind in sorted(kinds):
            labels = sorted(kinds[kind])
            shown = "" if kind in ("swift_library", "filegroup", *CLANG_KINDS) else ": " + ", ".join(labels)
            self.log(f"  {len(labels):4d} {kind}{shown}")
        self.log(f"  {swift['files']:4d} checked-in Swift files, {swift['bytes'] / 1e6:.1f} MB "
                 f"(generated sources not counted)")
        unsupported = sorted(kind for kind in kinds if "genrule" not in kind and kind not in (
            "swift_binary", "filegroup", "genrule", *SWIFT_KINDS, *CLANG_KINDS, *FRAMEWORK_KINDS))
        if unsupported:
            self.log("  kinds with no Swift-visible interface here (skipped as dependencies): " + ", ".join(unsupported))
        if external:
            self.log("  external repositories referenced: " + ", ".join(sorted(external)))
        for problem in problems:
            self.log(f"  PROBLEM {problem}")
        return not problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--module", metavar="TARGET",
                        help="check a swift_library from its current sources: label, package path or name")
    parser.add_argument("--extra", metavar="FILE", nargs="+", default=[],
                        help="with --module: compile these files as part of the module although its BUILD "
                             "globs do not match them (drafts kept outside the source tree)")
    parser.add_argument("--substitute", metavar="SOURCE=FILE", nargs="+", default=[],
                        help="with --module: compile FILE in place of the module's SOURCE (a draft of an "
                             "existing file, or its version from another commit)")
    parser.add_argument("--primary", metavar="FILE", nargs="+", default=[],
                        help="with --module: fully check only these source files of the module")
    parser.add_argument("--files", metavar="FILE", nargs="+", default=[],
                        help="check these Swift files as a module of their own")
    parser.add_argument("--module-name", "--imports-module-name", dest="module_name", default="AyuTypecheck",
                        help="module name for --files (default %(default)s)")
    parser.add_argument("--deps", metavar="TARGET", nargs="+",
                        help="dependencies of --files; default: those of " + ", ".join(DEFAULT_FILE_DEPENDENCIES)
                             + " that the files import")
    parser.add_argument("--ayu-app", action="store_true",
                        help="fully check every module outside the bridge that compiles a Swift file mentioning "
                             "AyuPlugin (found by search); with `--primary only`, check just those files")
    parser.add_argument("--closure", metavar="TARGET", help="print the dependency closure of a target and exit")
    parser.add_argument("--no-fetch", action="store_true",
                        help="never download single files of uninitialized git submodules from GitHub")
    parser.add_argument("--notes", action="store_true", help="list the dependencies that were skipped, and why")
    parser.add_argument("--configuration", choices=("release", "debug"), default="release",
                        help="release defines NDEBUG like the CI build (default), debug defines DEBUG")
    parser.add_argument("--cache", type=Path, default=DEFAULT_CACHE, help="cache directory (default %(default)s)")
    parser.add_argument("--jobs", type=int, default=max(2, min(8, (os.cpu_count() or 4) - 2)),
                        help="parallel frontend jobs of a full module check (default %(default)s)")
    parser.add_argument("--recheck", action="store_true", help="repeat a module check that was already clean")
    options = parser.parse_args()
    if not (options.module or options.files or options.closure or options.ayu_app):
        parser.error("give --module, --files, --ayu-app or --closure")
    primary_only = options.ayu_app and options.primary == ["only"] and not options.module
    if (options.primary and not primary_only or options.extra or options.substitute) and not options.module:
        parser.error("--primary, --extra and --substitute need --module")

    started = time.monotonic()
    try:
        builder = Builder(Toolchain(), options.cache.expanduser().resolve(), options.configuration, options.jobs,
                          fetch=not options.no_fetch)
        if options.closure:
            return 0 if builder.closure(*builder.workspace.resolve(options.closure)) else 2
        clean = True
        if options.module:
            clean = builder.check_module(*builder.workspace.resolve(options.module), options.extra,
                                         options.primary, options.recheck, options.substitute) and clean
        if options.files:
            clean = builder.check_files(options.files, options.module_name,
                                        options.deps or list(DEFAULT_FILE_DEPENDENCIES),
                                        bool(options.deps)) and clean
        if options.ayu_app:
            clean = builder.check_app(primary_only, options.recheck) and clean
        if options.notes:
            for label, reason in sorted(builder.skipped.items()):
                builder.log(f"note    dependency {label} skipped: {reason}")
        elif builder.skipped:
            builder.log(f"note    {len(builder.skipped)} dependencies have no Swift-visible part here "
                        f"(native builds, Rust, external repositories); --notes lists them")
        for stub, record in sorted(builder.stubbed.items()):
            builder.log(f"note    PLACEHOLDER module {stub} stands in for {record['label']} ({record['names']} names, "
                        f"{record['source']}); diagnostics that involve its importer {record['importer']} are "
                        f"not trustworthy")
        if builder.workspace.fetched:
            builder.log(f"note    fetched {len(builder.workspace.fetched)} files of uninitialized submodules into "
                        f"{builder.workspace.overlay}")
    except Failure as failure:
        print(f"error: {failure}", file=sys.stderr)
        return 2
    builder.log(f"{'clean' if clean else 'FAILED'} in {time.monotonic() - started:.1f}s")
    if not clean:
        return 1
    return 2 if builder.unchecked else 0


if __name__ == "__main__":
    sys.exit(main())
