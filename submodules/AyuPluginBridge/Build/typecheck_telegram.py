#!/usr/bin/env python3
"""Type-check Swift of this repository with swiftc only: TelegramCore, TelegramUI, the plugin wiring.

This is not a build: no Bazel, no Make.py, no xcodebuild, no object code, no linking of app code,
no app or IPA. The script reads the Bazel BUILD files (evaluated as Python with stub rules; Bazel
is never started), walks the dependency closure of a `swift_library` and, for every dependency,
  * emits a `.swiftmodule` with `swiftc -emit-module` (declarations only: function bodies of
    dependencies are not type-checked and their warnings are suppressed), several at a time,
  * writes a Clang module map for every `objc_library`/`cc_library` (headers only, nothing is
    compiled), with the `includes` and `defines` of its BUILD target,
  * runs the genrules that produce Swift sources or headers (TelegramApi from `swift_scheme.tl`
    with SwiftTL, FlatSerialization from `.fbs` with flatc 24.12.23 built from the source archive
    pinned in MODULE.bazel, the presentation strings, the Siri intent classes) and builds their
    host tools the way the BUILD files do. Genrules that build native libraries (ffmpeg, td,
    opus, ...) or need Rust are never run; C libraries whose headers they produce are left out.
Everything is cached outside the repository (default `~/Library/Caches/ayu-typecheck`), keyed by
a hash of the inputs: an unchanged dependency is never rebuilt and a clean check is remembered.
A module is rebuilt when a dependency's declarations change, not when only its function bodies do.
Concurrent runs share the cache safely. The first run downloads two archives.

What is not real, and is announced on every run that uses it:
  * FETCH: a file of an uninitialized git submodule that a BUILD file names is downloaded from
    the submodule's pinned commit on GitHub into the cache (never into the repository; no git
    state changes). Today: the BUILD file and C header of third-party/mtproto-engine.
  * PLACEHOLDER: a module that cannot be produced here at all (WalletEngineFFI is generated by a
    Rust toolchain from an uninitialized submodule) is replaced by a generated module that only
    declares the names its single importer (WalletContext) refers to. That importer is emitted
    without any of its bodies. Code that merely depends on the importer is checked for real; code
    that uses the placeholder's types is not.

Check every module outside the bridge that compiles plugin wiring (files mentioning AyuPlugin are
found by search), all bodies, with each module's own copts:
    python3 -B submodules/AyuPluginBridge/Build/typecheck_telegram.py --ayu-app
Check one module from its current sources, all bodies, with its own copts (`-warnings-as-errors`);
this also runs the SIL diagnostics that `swiftc -typecheck` skips:
    python3 -B .../typecheck_telegram.py --module TelegramCore        (or TelegramUI, //pkg:target)
Include drafts kept outside the source tree, or compile a draft in place of an existing file:
    python3 -B .../typecheck_telegram.py --module TelegramCore --extra /scratch/Draft.swift
    python3 -B .../typecheck_telegram.py --module TelegramUI --substitute submodules/TelegramUI/Sources/X.swift=/scratch/X.swift
Check only the named files of the module in full (about a second). This reports every error
located in those files, including their use of the rest of the module; it does not report errors
that the change causes in other files of the module:
    python3 -B .../typecheck_telegram.py --module TelegramUI --primary submodules/TelegramUI/Sources/X.swift
Check loose files as a module of their own (a future small target) against the modules they import:
    python3 -B .../typecheck_telegram.py --files a.swift b.swift --module-name MyPlugins [--deps //pkg:target ...]
Print what a target would need, without compiling anything:
    python3 -B .../typecheck_telegram.py --closure //submodules/TelegramUI

Not checked: Bazel visibility and the Postbox import allow-lists, Objective-C, C and C++ sources,
linking, optimizer-only failures of the release build, and anything that needs an SDK newer than
the installed Xcode's (Display's own bodies use an iOS 27.1 API; it still works as a dependency).

Exit status: 0 clean, 1 diagnostics in the code under test, 2 something could not be prepared or
checked (unsupported BUILD construct, uninitialized git submodule, failed generator or dependency).
"""

