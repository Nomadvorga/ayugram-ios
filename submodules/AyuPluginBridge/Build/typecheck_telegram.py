class Toolchain:
    def __init__(self) -> None:
        candidates = []
        if os.environ.get("DEVELOPER_DIR"):
            candidates.append(Path(os.environ["DEVELOPER_DIR"]))
        candidates += sorted(Path("/Applications").glob("Xcode*.app/Contents/Developer"))
        for candidate in candidates:
            if (candidate / "Platforms" / "iPhoneOS.platform").is_dir():
                self.developer = candidate
                break
        else:
            raise Failure("No Xcode with the iPhoneOS platform found; set DEVELOPER_DIR.")
        self.environment = dict(os.environ, DEVELOPER_DIR=str(self.developer))
        self.version = self.xcrun(["swiftc", "--version"]).stdout.strip().replace("\n", " ")
        self._sdks: dict[str, str] = {}

    def xcrun(self, arguments: list[str], cwd: Path | None = None) -> subprocess.CompletedProcess:
        return subprocess.run(["xcrun", *arguments], env=self.environment, cwd=cwd, text=True,
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT)

    def sdk(self, name: str) -> str:
        if name not in self._sdks:
            self._sdks[name] = self.xcrun(["--sdk", name, "--show-sdk-path"]).stdout.strip()
        return self._sdks[name]


