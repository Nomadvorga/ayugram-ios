"""Generate the searchable Android resource inventory from the pinned source manifest."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    source = ROOT / "submodules/TelegramPresentationData/UIIconSources/android-inventory.json"
    inventory = json.loads(source.read_text(encoding="utf-8"))
    keys = sorted(set().union(*(set(pack["aliases"]) for pack in inventory.values())))
    output = ROOT / "AyuGram/SGSimpleSettings/Sources/ExteraUIIconCatalog.swift"
    output.write_text("// Generated by tools/generate_extera_ui_icon_catalog.py from the pinned Android inventory.\n"
                      "// Unconsumed keys are retained for Android export; this is not an iOS coverage claim.\n"
                      "public enum ExteraUIIconCatalog {\n    public static let androidResources: [String] = [\n" +
                      "\n".join('        "' + key + '",' for key in keys) + "\n    ]\n}\n", encoding="utf-8")
    print(f"Generated {len(keys)} exact Android resource keys.")


if __name__ == "__main__":
    main()
